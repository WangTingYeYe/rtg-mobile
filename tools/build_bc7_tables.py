#!/usr/bin/env python3
"""Regenerate the pure-C BC7 partition/anchor table from the vendored decoder."""
import ast
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
header=(root/'rtg/third_party/bcdec/bcdec.h').read_text()
start=header.index('static unsigned char partition_sets[2][64][4][4]')
start=header.index('{',start);depth=0
for end in range(start,len(header)):
    depth+=(header[end]=='{')-(header[end]=='}')
    if depth==0:break
literal=re.sub(r'/\*.*?\*/','',header[start:end+1],flags=re.S)
table=ast.literal_eval(literal.replace('{','[').replace('}',']'))
flat=[v for partition_type in table for partition in partition_type for row in partition for v in row]
assert len(flat)==2048 and all(0<=v<=130 for v in flat)
words=[sum(flat[i+j]<<(j*8) for j in range(4)) for i in range(0,len(flat),4)]
for base in range(0,len(flat),16):
    mask=sum(1<<i for i,v in enumerate(flat[base:base+16]) if v&128)
    assert bin(mask).count('1')==(2 if base<1024 else 3)
    words.append(mask)
license_text=header[header.index('ALTERNATIVE A - MIT License'):header.index('ALTERNATIVE B - The Unlicense')]
license_text=license_text[:license_text.rfind('------------------------------------------------------------------------------')].strip()
text='// Generated by tools/build_bc7_tables.py; do not edit.\n/*\n'+license_text+'\n*/\n#pragma once\n#include <stdint.h>\nstatic const uint32_t nvn_bc7_tables[640]={\n'
text+=',\n'.join(','.join('0x%08xu'%v for v in words[i:i+8]) for i in range(0,len(words),8))+'\n};\n'
(root/'rtg/gfx/tex/nvn_bc7_tables.h').write_text(text)
