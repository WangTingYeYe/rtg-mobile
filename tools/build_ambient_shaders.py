#!/usr/bin/env python3
"""Regenerate nvn_vk_ambient_spv.h from the GLSL sources in rtg/gfx/nvn/ambient.

The APK builds from the generated header, so glslangValidator is only needed
when the shaders change. Run from the repository root.
"""
import shutil
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'rtg/gfx/nvn/ambient'
OUTPUT = ROOT / 'rtg/gfx/nvn/nvn_vk_ambient_spv.h'
SHADERS = (('ambient.vert', 'vert', 'filter_ambient_vert'),
           ('ambient_map.frag', 'frag', 'filter_ambient_map_frag'),
           ('ambient_bars.frag', 'frag', 'filter_ambient_bars_frag'))


def main():
    tool = shutil.which('glslangValidator')
    if not tool:
        raise SystemExit('glslangValidator is required to rebuild the ambient shaders')
    arrays = []
    for name, stage, symbol in SHADERS:
        binary = SOURCE / (name.rsplit('.', 1)[0] + '.spv')
        subprocess.run([tool, '-V', '--target-env', 'vulkan1.1', '-S', stage,
                        str(SOURCE / name), '-o', str(binary)], check=True)
        data = binary.read_bytes()
        if len(data) % 4 or struct.unpack_from('<I', data)[0] != 0x07230203:
            raise SystemExit(f'{name}: invalid SPIR-V')
        words = struct.unpack(f'<{len(data) // 4}I', data)
        rows = []
        for at in range(0, len(words), 8):
            rows.append('    ' + ', '.join(f'0x{word:08x}u' for word in words[at:at + 8]) + ',')
        arrays.append(f'static const uint32_t {symbol}[] = {{\n' + '\n'.join(rows) + '\n};\n')
    OUTPUT.write_text('/* Generated by tools/build_ambient_shaders.py; do not edit. */\n'
                      '#pragma once\n#include <stdint.h>\n\n' + '\n'.join(arrays))
    print(f'Wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()